}

/// Full LLVM IR analysis of a Go function's FFI calls.
///
/// Similar to Python adapter, this is a placeholder that returns metadata
/// without full IR walking. The classifyCall() method provides the practical
/// per-call classification.
pub fn analyzeFunction(
    self_ptr: *const adapter_mod.LanguageAdapter,
    func_opaque: *anyopaque,
    ctx: adapter_mod.ContextPtr,
    allocator: std.mem.Allocator,
) !types.AdapterAnalysis {
    _ = ctx;

    var result = try types.AdapterAnalysis.init(allocator, self_ptr.language);
    errdefer result.deinit();

    const llvm_func: c.LLVMValueRef = @ptrCast(@alignCast(func_opaque));

    if (c.LLVMIsDeclaration(llvm_func) != 0) {
        result.confidence = 0.1;
        return result;
    }

    var bb_iter = c.LLVMGetFirstBasicBlock(llvm_func);

    while (bb_iter != null) : (bb_iter = c.LLVMGetNextBasicBlock(bb_iter)) {
        const bb = bb_iter.?;

        var inst_iter = c.LLVMGetFirstInstruction(bb);

        while (inst_iter != null) : (inst_iter = c.LLVMGetNextInstruction(inst_iter)) {
            const inst = inst_iter.?;

            const opcode = c.LLVMGetInstructionOpcode(inst);
            if (opcode != c.LLVMCall) continue;

            const called_value = c.LLVMGetCalledValue(inst);
            if (called_value == null) continue;

            const callee_name_ptr = c.LLVMGetValueName(called_value);
            if (callee_name_ptr == null) continue;
            const callee_name = std.mem.span(callee_name_ptr);

            const classification = classifyCall(self_ptr, callee_name);

            if (classification == .unknown) continue;

            const inst_addr: u64 = @intFromPtr(inst);
            const call_info = types.FFICallInfo.init(
                inst_addr,
                callee_name,
                classification,
                0.88,
                .go,
            );

            try result.addCall(call_info);

            if (classification == .returns_owned) {
                result.refcount_increments += 1;
            } else if (classification == .consumes_arg) {
                result.refcount_decrements += 1;
            }
        }
    }

    result.refcount_balance = @as(i32, @intCast(result.refcount_increments)) -
        @as(i32, @intCast(result.refcount_decrements));

    if (result.refcount_balance > 0) {
        result.has_potential_leak = true;
        result.leak_severity = if (result.refcount_balance > 2) .high else .medium;
    }

    result.is_analyzed = true;
    result.confidence = if (result.ffi_calls.items.len > 0) 0.88 else 0.15;

    return result;
}

/// Detect if a function name is a cgo-generated wrapper.
///
/// The cgo tool generates wrapper functions with the _Cgo_ prefix
/// to bridge Go and C calling conventions. These are the primary
/// FFI boundary indicators in compiled Go code.
pub fn isCGoWrapper(func_name: []const u8) bool {
    if (std.mem.startsWith(u8, func_name, CGO_WRAPPER_PREFIX)) return true;
    for (CGO_PATTERNS) |pattern| {
        if (std.mem.indexOf(u8, func_name, pattern) != null) return true;
    }
    return false;
}

/// Detect if a function is a Go runtime internal function.
///
/// Checks against the comprehensive RUNTIME_FUNCTIONS table plus
/// the broad "runtime." prefix catch-all for any runtime function
/// not explicitly listed.
pub fn isRuntimeFunction(func_name: []const u8) bool {
    // Check explicit table first
    for (RUNTIME_FUNCTIONS) |f| {
        if (std.mem.indexOf(u8, func_name, f) != null) return true;
    }

    // Broad prefix check for runtime package functions
    if (std.mem.startsWith(u8, func_name, "runtime.")) return true;

    return false;
}

/// Check if a function looks like a deferred cleanup call.
///
/// In Go, `defer C.free(ptr)` is the standard pattern for ensuring
/// C-allocated memory is released. These functions typically appear
/// in defer blocks and are called at function exit.
pub fn isLikelyDeferredCleanup(func_name: []const u8) bool {
    // C.* prefixed functions in defer context
    if (std.mem.startsWith(u8, func_name, "C.")) return true;
    // Common cleanup names
    if (std.mem.eql(u8, func_name, "close")) return true;
    if (std.mem.eql(u8, func_name, "destroy")) return true;
    return false;
}

/// Detect cross-language free pattern: Go allocator + C deallocator.
///
/// This is a common source of memory safety bugs in Go cgo code:
///   - runtime.mallocgc (Go GC heap) + free (C) → undefined behavior
///   - _cgo_allocate (Go) + free (C) → cross-language free
///   - C.CString (Go-allocated C memory) correctly freed by C.free ✓
pub fn isCrossLanguageFreePattern(go_alloc: []const u8, c_free: []const u8) bool {
    const go_allocators = [_][]const u8{
        "runtime.mallocgc",
        "runtime.newobject",
        "_cgo_allocate",
        "_Cfunc_GoMalloc",
        "runtime.alloc", // TinyGo
    };

    const c_deallocators = [_][]const u8{
        "free",
        "C.free",
        "_cgo_free",
        "_Cgo_free",
        "_Cfunc_GoFree",
    };

    var is_go_alloc = false;
    for (go_allocators) |alloc| {
        if (std.mem.indexOf(u8, go_alloc, alloc) != null) {
            is_go_alloc = true;
            break;
        }
    }

    var is_c_free = false;
    for (c_deallocators) |dealloc| {
        if (std.mem.indexOf(u8, c_free, dealloc) != null) {
            is_c_free = true;
            break;
        }
    }

    return is_go_alloc and is_c_free;
}

/// Detect potential memory leak pattern: C allocation without matching free.
///
/// Common in Go cgo when:
///   - C.CString / C.CBytes allocated but result discarded or leaked
///   - C.malloc called but C.free never called on the result
///   - Return value from owning function escapes without cleanup
pub fn isPotentialLeakPattern(alloc_call: []const u8, has_matching_free: bool) bool {
    const owning_calls = [_][]const u8{
        "C.CString",
        "C.CBytes",
        "C.malloc",
        "C.calloc",
        "C.strdup",
        "_Cgo_malloc",
    };

    var is_owning = false;
    for (owning_calls) |call| {
        if (std.mem.indexOf(u8, alloc_call, call) != null) {
            is_owning = true;
            break;
        }
    }

    return is_owning and !has_matching_free;
}

