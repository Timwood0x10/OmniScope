/// Singleton instance of the Go language adapter.
pub const instance = adapter_mod.LanguageAdapter{
    .name = "go",
    .language = .go,
    .memory_model = .hybrid,
    .vtable = .{
        .analyzeFn = analyzeFunction,
        .classifyFn = classifyCall,
        .suppressFn = shouldSuppress,
        .owningPatternsFn = getOwningPatterns,
        .borrowingPatternsFn = getBorrowingPatterns,
    },
};

/// Classify a Go/cgo FFI call by callee name.
///
/// Go's model is different from Python:
///   - C.malloc / C.calloc → returns_owned (caller gets raw C heap pointer)
///   - C.free → consumes_arg (takes ownership of C heap pointer)
///   - runtime.* → suppressed (not real FFI)
///   - _Cgo_* → wrapper boundary (depends on wrapped function)
pub fn classifyCall(
    self_ptr: *const adapter_mod.LanguageAdapter,
    callee_name: []const u8,
) FFISemantics {
    _ = self_ptr;

    // C allocation wrappers return owned C pointers
    for (C_STDLIB_WRAPPERS) |f| {
        if (std.mem.eql(u8, callee_name, f)) {
            // C.free consumes; others return owned
            if (std.mem.indexOf(u8, callee_name, ".free") != null) {
                return .consumes_arg;
            }
            if (std.mem.indexOf(u8, callee_name, ".malloc") != null or
                std.mem.indexOf(u8, callee_name, ".calloc") != null or
                std.mem.indexOf(u8, callee_name, ".realloc") != null)
            {
                return .returns_owned;
            }
            return .unknown;
        }
    }

    // cgo wrappers: classify based on what they wrap
    if (isCGoWrapper(callee_name)) {
        if (std.mem.indexOf(u8, callee_name, "free") != null) return .consumes_arg;
        if (std.mem.indexOf(u8, callee_name, "malloc") != null) return .returns_owned;
        return .unknown;
    }

    return .unknown;
}

/// Check if a function should be suppressed from FFI analysis.
///
/// Go runtime internal functions (runtime.*) and cgo infrastructure
/// should not be treated as FFI boundaries. Only user-level C calls
/// through cgo are real boundaries.
pub fn shouldSuppress(
    self_ptr: *const adapter_mod.LanguageAdapter,
    func_name: []const u8,
) bool {
    _ = self_ptr;

    // Suppress all runtime.* functions
    if (isRuntimeFunction(func_name)) return true;

    // Suppress known runtime-adjacent prefixes
    const suppress_prefixes = [_][]const u8{
        "runtime.",
        "internal/abi.",
        "internal/task.",
    };
    for (suppress_prefixes) |prefix| {
        if (std.mem.startsWith(u8, func_name, prefix)) return true;
    }

    return false;
}

/// Return owning pattern list for Go: C allocators.
pub fn getOwningPatterns(self_ptr: *const adapter_mod.LanguageAdapter) []const []const u8 {
    _ = self_ptr;
    return &C_STDLIB_WRAPPERS;
}

/// Return borrowing pattern list for Go: mostly empty since Go/C borrows rarely.
pub fn getBorrowingPatterns(self_ptr: *const adapter_mod.LanguageAdapter) []const []const u8 {
    _ = self_ptr;
    return &[_][]const u8{};
}

/// Full LLVM IR analysis of a Go function's FFI calls.
///
/// Similar to Python adapter, this is a placeholder that returns metadata
/// without full IR walking. The classifyCall() method provides the practical
/// per-call classification.
pub fn analyzeFunction(
    self_ptr: *const adapter_mod.LanguageAdapter,
    func_opaque: *anyopaque,
    ctx: adapter_mod.ContextPtr,
    allocator: std.mem.Allocator,
) !types.AdapterAnalysis {
    _ = func_opaque;
    _ = ctx;

    var result = try types.AdapterAnalysis.init(allocator, self_ptr.language);
    errdefer result.deinit();

    result.confidence = 0.80;
    return result;
}

/// Detect if a function name is a cgo-generated wrapper.
///
/// The cgo tool generates wrapper functions with the _Cgo_ prefix
/// to bridge Go and C calling conventions. These are the primary
/// FFI boundary indicators in compiled Go code.
pub fn isCGoWrapper(func_name: []const u8) bool {
    if (std.mem.startsWith(u8, func_name, CGO_WRAPPER_PREFIX)) return true;
    for (CGO_PATTERNS) |pattern| {
        if (std.mem.indexOf(u8, func_name, pattern) != null) return true;
    }
    return false;
}

/// Detect if a function is a Go runtime internal function.
///
/// Checks against the comprehensive RUNTIME_FUNCTIONS table plus
/// the broad "runtime." prefix catch-all for any runtime function
/// not explicitly listed.
pub fn isRuntimeFunction(func_name: []const u8) bool {
    // Check explicit table first
    for (RUNTIME_FUNCTIONS) |f| {
        if (std.mem.indexOf(u8, func_name, f) != null) return true;
    }

    // Broad prefix check for runtime package functions
    if (std.mem.startsWith(u8, func_name, "runtime.")) return true;

    return false;
}

/// Check if a function looks like a deferred cleanup call.
///
/// In Go, `defer C.free(ptr)` is the standard pattern for ensuring
/// C-allocated memory is released. These functions typically appear
/// in defer blocks and are called at function exit.
pub fn isLikelyDeferredCleanup(func_name: []const u8) bool {
    // C.* prefixed functions in defer context
    if (std.mem.startsWith(u8, func_name, "C.")) return true;
    // Common cleanup names
    if (std.mem.eql(u8, func_name, "close")) return true;
    if (std.mem.eql(u8, func_name, "destroy")) return true;
    return false;
}

