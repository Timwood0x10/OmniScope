//! Go (cgo) FFI Adapter — Handles Go's cgo interop patterns.
//!
//! Key Go FFI concepts modeled here:
//!
//!   - **defer mechanism**: Cleanup scheduled at function end (defer C.free(ptr))
//!     This is Go's closest analog to RAII — resources are guaranteed to be
//!     cleaned up when the function returns, even on panic paths.
//!
//!   - **runtime.SetFinalizer**: Similar to C++ destructors or Java finalizers.
//!     The GC calls the registered function when an object is collected.
//!     Not deterministic — can't rely on it for timely resource release.
//!
//!   - **cgo wrapper functions** (_Cgo_*): Generated by the cgo tool to bridge
//!     between Go calling conventions and C ABI. These are the actual FFI
//!     boundary points in compiled Go code.
//!
//!   - **Go runtime manages goroutine stack**: Go pointers passed to C must
//!     not contain Go pointers themselves (the "Go pointer passing rules").
//!     Violations cause runtime crashes, not just memory corruption.
//!
//! ## Reference
//!   - https://go.dev/cmd/cgo/ (cgo command documentation)
//!   - TinyGo IR spec: docs/en/ir-specs/TINYGO_IR_SPEC.md

