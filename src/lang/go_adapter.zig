/// Prefix for cgo-generated wrapper functions.
///
/// The cgo tool generates these bridge functions automatically:
///   - _Cgo_malloc → wraps C malloc with Go calling convention
///   - _Cgo_free  → wraps C free
///   - _Cgo_ptr   → pointer conversion helpers
pub const CGO_WRAPPER_PREFIX = "_Cgo_";

/// Additional cgo-related function prefixes/patterns beyond _Cgo_*.
pub const CGO_PATTERNS = [_][]const u8{
    "_cgo_",
    "_Cfunc_",
    "_Ctype_",
    "crosscall2", // Runtime cross-call bridge
    "runtime.cgocall",
    "unionfield_", // TinyGo union field access
    "bitfield_", // TinyGo bitfield access
};

/// Common C standard library calls wrapped by Go via cgo.
///
/// When Go code calls C.malloc / C.free etc., the compiler generates
/// a _Cgo_* wrapper. These are the underlying C functions that the
/// wrappers delegate to.
pub const C_STDLIB_WRAPPERS = [_][]const u8{
    "C.malloc",
    "C.calloc",
    "C.realloc",
    "C.free",
